// Natural Arabic translation helper function for structured templates, AEO, SEO, enterprise, platform, and UI terms
function translateEnglishText(key, text) {
  if (exactDictionary[key]) return exactDictionary[key];
  if (!text || typeof text !== 'string') return text;
  
  // Trim
  const trimmed = text.trim();
  if (exactDictionary[trimmed]) return exactDictionary[trimmed];

  // Specific patterns
  if (trimmed.startsWith('http://') || trimmed.startsWith('https://')) return trimmed;
  if (/^#[0-9a-fA-F]{3,6}$/.test(trimmed)) return trimmed;
  if (trimmed === 'FreeQRBarcodes.com' || trimmed === 'FreeQRBarcodes' || trimmed === 'FreeQRGen.pro' || trimmed === 'Free QR Generator' || trimmed === 'iSolutions' || trimmed === 'QR Code') return trimmed;

  // Let's handle variables like {count}, {name}, etc.
  return null;
}

