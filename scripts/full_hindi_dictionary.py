def get_real_untranslated_words(val):
    if not isinstance(val, str):
        return []
    stripped = re.sub(r'\{\{[^}]+\}\}', '', val)
    stripped = re.sub(r'\{[^}]+\}', '', stripped)
    stripped = re.sub(r'<[^>]+>', '', stripped)
    words = re.findall(r'[a-zA-Z]+', stripped)
    return [w for w in words if w.upper() not in ALLOWED_EXACT]

