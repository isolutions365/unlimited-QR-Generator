def translate_text(text):
    if not isinstance(text, str):
        return text
    res = text
    for eng, hin in EN_HI_DICT.items():
        pattern = r'\b' + re.escape(eng) + r'\b'
        res = re.sub(pattern, hin, res, flags=re.IGNORECASE)
    return res

fixed_keys = 0
for k in en_data.keys():
    en_val = en_data[k]
    hi_val = hi_data.get(k, "")
    words = get_real_untranslated_words(hi_val)
    if len(words) > 0:
        source = hi_val if hi_val else en_val
        translated = translate_text(source)
        hi_data[k] = translated
        fixed_keys += 1

print(f"Fixed remaining English words in {fixed_keys} keys.")

